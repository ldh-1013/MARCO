using UnityEngine;

namespace Marco.Core.Spatial
{
    /// <summary>
    /// **GAP-71 — 소리 인지 거리에 수직 성분(Y)을 넣는가. 이 파일이 그 결정의 유일한 소유자다.**
    ///
    /// <para>
    /// <b>결정: 넣는다(3D).</b> 근거 세 가지.
    /// </para>
    ///
    /// <para>
    /// ① <b>차폐 레이캐스트가 3D라서다.</b> §5.6은 1차 컷(straightDist &gt; baseRadius)을 통과한
    /// 뒤 같은 두 점 사이로 레이를 쏜다. 컷을 XZ 평면에서 재고 레이는 3D로 쏘면 <b>두 판정이
    /// 서로 다른 선을 본다</b> — 2층 리스너가 XZ 기준으로는 반경 안이라 컷을 통과하고, 실제
    /// 레이는 층간 바닥을 뚫는 전혀 다른 경로가 된다. 컷과 레이가 같은 선이어야 한다.
    /// </para>
    ///
    /// <para>
    /// ② <b>수직 감쇠는 이미 층간 바닥이 담당한다.</b> §5.6 [v0.4]가 층간 바닥을 Wall 2장
    /// (×0.25)으로 못박았다. 거리에 Y를 또 넣는 게 아니라 <b>Y를 빼면</b> 2층 소리가
    /// 수평 거리만으로 판정되어 ×0.25와 이중으로 어긋난다. 반대로 §10.2-1 밸브 배치 검증은
    /// 이 벽 수 모델로 여유 0.32m(C↔D)까지 계산해 둔 상태라, 거리 척도를 바꾸면 그 검증이
    /// 전부 무효가 된다.
    /// </para>
    ///
    /// <para>
    /// ③ <b>태그 판정이 3D여야 §6.5-3이 성립한다.</b> "수심 3.5m &gt; 태그 반경 1.2m이므로
    /// 술래는 수면에서 배수구에 닿을 수 없다"는 최후 생존자 페이즈의 공정성 논거 전체가
    /// 수직 성분에 걸려 있다. 인지 거리를 2D로 두면 한 시스템 안에 2D 척도와 3D 척도가
    /// 공존하게 되는데, 그것이 지시서가 경고한 "두 곳에서 다르게 재면 사고다"의 실체다.
    /// </para>
    ///
    /// <para>
    /// <b>이 함수를 2D로 바꾸려면</b> 위 ①②③을 모두 다시 판단하고 §10.2-1 배치 검증을
    /// 재산출해야 한다. 한 줄 고치고 끝나는 변경이 아니다.
    /// </para>
    ///
    /// <para>
    /// <b>태그 판정(<c>TagRules</c>)은 의도적으로 이 함수에 위임하지 않는다.</b> 위임하면
    /// 누군가 "소리만 2D로" 바꿨을 때 §6.5-3이 조용히 무너진다. 그쪽은 항상 3D라는 것이
    /// 규칙 자체이므로 <c>Vector3.Distance</c>를 직접 쓰고 그 이유를 주석으로 남겼다.
    /// </para>
    /// </summary>
    public static class DistanceMetric
    {
        /// <summary>
        /// §5.6 의사코드의 <c>Distance(pulse.position, listener.position)</c>.
        /// 소리 인지·유인·공포 반경 판정이 전부 이 하나를 쓴다.
        /// </summary>
        public static float Perceived(Vector3 a, Vector3 b)
        {
            return Vector3.Distance(a, b);
        }
    }
}
